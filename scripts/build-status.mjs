#!/usr/bin/env node
// Builds the compatibility status ("can I use") from the provider adapters, which are the
// single source of truth:
//   compatibility/STATUS.md   human-readable table
//   site/status.json          data for the status page
// Usage: node scripts/build-status.mjs          write both files
//        node scripts/build-status.mjs --check  fail if they are out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { defaultVariant, providers } from "../lib/providers/index.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PLATFORMS = ["ios", "android", "desktop"];
const PLATFORM_NAME = { ios: "iOS", android: "Android", desktop: "Desktop" };
const ICON = { documented: "✅", observed: "🟢", conflicting: "🟡", unverified: "⚪", unsupported: "❌" };

const status = {
  generatedFrom: "lib/providers/*.ts",
  evidenceLevels: {
    documented: "The provider's own documentation describes it.",
    observed: "Seen working in device tests or by several third parties. Undocumented: it can break at any time.",
    conflicting: "Sources disagree. Needs a device test.",
    unverified: "Plausible, but no reliable report either way.",
    unsupported: "Known not to work, or no mechanism exists.",
  },
  providers: providers.map((p) => {
    const sample = "hello";
    const def = defaultVariant(p, sample);
    return {
      id: p.id,
      name: p.name,
      homeUrl: p.homeUrl,
      lastVerified: p.lastVerified,
      verificationMethod: p.verificationMethod,
      defaultStrategy: def.strategy,
      nativeAppLaunch: p.nativeAppLaunch,
      promptPrefill: p.promptPrefill,
      autoSubmit: p.autoSubmit,
      autoSubmitNote: p.autoSubmitNote,
      requiresLogin: p.requiresLogin,
      fallback: p.fallback,
      safeUrlLength: p.safeUrlLength,
      variants: p.variants("{prompt}").map((v) => ({
        id: v.id,
        url: v.url.replace(encodeURIComponent("{prompt}"), "{prompt}"),
        strategy: v.strategy,
        experimental: v.experimental,
        evidence: v.evidence,
        note: v.note,
      })),
      docs: p.docs,
    };
  }),
};

const cell = (e) => `${ICON[e]} ${e}`;
const lines = [];
lines.push("# Compatibility status", "");
lines.push("<!-- Generated by scripts/build-status.mjs from lib/providers/*.ts. Do not edit by hand. -->", "");
lines.push(
  "What works today when a link tries to open an assistant with a prompt. \"Opened\" and \"prompt arrived\" are separate questions, so they are separate tables.",
  "",
  "**No provider documents a prefill URL.** Everything marked *observed* is undocumented behavior and can change without notice.",
  "",
);
lines.push("| Level | Meaning |", "|---|---|");
for (const [k, v] of Object.entries(status.evidenceLevels)) lines.push(`| ${cell(k)} | ${v} |`);
lines.push("");

for (const [title, key] of [["Native app opens from a link", "nativeAppLaunch"], ["Prompt arrives in the chat box", "promptPrefill"]]) {
  lines.push(`## ${title}`, "", `| Assistant | ${PLATFORMS.map((x) => PLATFORM_NAME[x]).join(" | ")} |`, `|---|${PLATFORMS.map(() => "---").join("|")}|`);
  for (const p of status.providers) lines.push(`| ${p.name} | ${PLATFORMS.map((x) => cell(p[key][x])).join(" | ")} |`);
  lines.push("");
}

lines.push("## Sent without the person tapping send", "", "| Assistant | Evidence | Detail |", "|---|---|---|");
for (const p of status.providers) lines.push(`| ${p.name} | ${cell(p.autoSubmit)} | ${p.autoSubmitNote} |`);
lines.push("");

lines.push("## Launch variants", "", "| Assistant | Variant | URL | Evidence | Default | Note |", "|---|---|---|---|---|---|");
for (const p of status.providers) {
  for (const v of p.variants) {
    lines.push(`| ${p.name} | \`${v.id}\` | \`${v.url}\` | ${cell(v.evidence)} | ${v.experimental ? "no (experimental)" : "yes"} | ${v.note} |`);
  }
}
lines.push("");

lines.push("## Per assistant", "");
for (const p of status.providers) {
  lines.push(`### ${p.name}`, "");
  lines.push(`- **Last verified:** ${p.lastVerified} (${p.verificationMethod})`);
  lines.push(`- **Sign-in:** ${p.requiresLogin}`);
  lines.push(`- **Fallback:** ${p.fallback}`);
  lines.push(`- **References:**`);
  for (const d of p.docs) lines.push(`  - [${d.title}](${d.url}) (${d.kind})${d.note ? `: ${d.note}` : ""}`);
  lines.push("");
}
lines.push("Raw device results: [`results.csv`](results.csv). How to test your own device: [`PROTOCOL.md`](PROTOCOL.md).", "");

const outputs = [
  [join(root, "compatibility/STATUS.md"), lines.join("\n")],
  [join(root, "site/status.json"), JSON.stringify(status, null, 2) + "\n"],
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const [file, content] of outputs) {
    let current = "";
    try { current = readFileSync(file, "utf8"); } catch { /* missing */ }
    if (current !== content) { stale = true; console.error(`Out of date: ${file}`); }
  }
  if (stale) { console.error("Run `npm run status` and commit the result."); process.exit(1); }
  console.log("Status files are up to date.");
} else {
  for (const [file, content] of outputs) { writeFileSync(file, content); console.log(`wrote ${file}`); }
}
